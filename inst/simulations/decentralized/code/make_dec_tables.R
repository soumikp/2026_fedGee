# Web Appendix I tables (Web Tables S1-S2) from the decentralized simulation (v4).
# Per scenario, no averaging.
# Run from inst/simulations/decentralized:   Rscript code/make_dec_tables.R
# If the raw output (output/sim_results_v4/, not in the repository) is present,
# the per-scenario summary is recomputed from it and saved to results/.
# Otherwise the tracked summary results/dec_v4_summary.rds is used.
# The spectral quantities rho depend only on the network and are always recomputed.
suppressPackageStartupMessages(library(dplyr))
RAW_DIR <- "output/sim_results_v4"
SUMMARY <- "results/dec_v4_summary.rds"
TEX_OUT <- "../../manuscript/tables/supp_dec_tables.tex"
env <- new.env(); sys.source("code/01_decentralized_fedgee.R", envir = env)
part <- function(K, size = 5) { rid <- rep(seq_len(max(1, ceiling(K / size))), each = size, length.out = K)
  list(region_id = rid, hub_sites = vapply(unique(rid), function(r) which(rid == r)[1], integer(1))) }
Wof <- function(K, s) { w <- if (s == "visn") { pt <- part(K); env$build_weight_matrix(K, structure = "visn", region_id = pt$region_id, hub_sites = pt$hub_sites) }
  else if (s == "ring") env$build_weight_matrix(K, structure = "ring", K_neigh = 2)
  else if (s == "hub") env$build_weight_matrix(K, structure = "hub", hub = 1)
  else env$build_weight_matrix(K, structure = "complete"); if (is.list(w)) w$W else w }
rho <- function(W) sort(abs(eigen(W, symmetric = TRUE, only.values = TRUE)$values), decreasing = TRUE)[2]
Ks <- c(5, 10, 15, 25, 50, 100); nets <- c("complete", "visn", "ring", "hub")
invisible(capture.output(R <- suppressMessages(outer(Ks, nets, Vectorize(function(K, s) rho(Wof(K, s))))), type = "output"))
dimnames(R) <- list(Ks, nets)
if (dir.exists(RAW_DIR)) {
  d <- bind_rows(lapply(list.files(RAW_DIR, full.names = TRUE), readRDS))
  keys <- c("K", "rho_H", "beta_0", "include_teaching")
  m <- c(fed_site = "cen", dec_complete = "complete", dec_visn = "visn", dec_ring = "ring", dec_hub = "hub")
  s <- d |> filter(method %in% names(m)) |> mutate(net = m[method]) |> group_by(across(all_of(keys)), net) |>
    summarise(cov = mean(covers_t, na.rm = TRUE), sesd = mean(se_hat, na.rm = TRUE) / sd(beta_hat, na.rm = TRUE),
              bsd = mean(bias, na.rm = TRUE) / sd(beta_hat, na.rm = TRUE), n = n(), .groups = "drop")
  w <- tidyr::pivot_wider(s, id_cols = c(all_of(keys)), names_from = net, values_from = c(cov, sesd, bsd, n)) |>
    arrange(K, include_teaching, rho_H, desc(beta_0))
  saveRDS(list(rho = R, table = w), SUMMARY)
} else {
  message("Raw output not found; using ", SUMMARY)
  w <- readRDS(SUMMARY)$table
}
