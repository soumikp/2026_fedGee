    "& & & & \\multicolumn{5}{c}{Coverage} & \\multicolumn{5}{c}{SE/SD}\\\\\n\\cmidrule(lr){5-9}\\cmidrule(lr){10-14}\n",
    "$K$ & $\\rho_H$ & Prev. & $p$ & Cen. & Comp. & Reg. & Ring & Hub & Cen. & Comp. & Reg. & Ring & Hub\\\\\n\\midrule\n\\endfirsthead\n",
    "\\toprule\n$K$ & $\\rho_H$ & Prev. & $p$ & Cen. & Comp. & Reg. & Ring & Hub & Cen. & Comp. & Reg. & Ring & Hub\\\\\n\\midrule\n\\endhead\n\\bottomrule\n\\endfoot\n", sep = "")
