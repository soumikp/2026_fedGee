  K, rho_H, ifelse(beta_0 == -3, "0.07", "0.30"), ifelse(include_teaching, 3L, 2L),
  f3(cov_cen), f3(cov_complete), f3(cov_visn), f3(cov_ring), f3(cov_hub),
  f3(sesd_cen), f3(sesd_complete), f3(sesd_visn), f3(sesd_ring), f3(sesd_hub)), sep = ""))
